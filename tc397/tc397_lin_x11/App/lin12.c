/* ---------- TLIN1024 EN (= board SLP_N, high = normal) ---------- */
void lin_xcvr_init(void)
{
    IfxPort_setPinModeOutput(&MODULE_P02, 8, IfxPort_OutputMode_pushPull, IfxPort_OutputIdx_general);
    IfxPort_setPinHigh(&MODULE_P02, 8);    /* LIN0-3 */
    IfxPort_setPinModeOutput(&MODULE_P00, 11, IfxPort_OutputMode_pushPull, IfxPort_OutputIdx_general);
    IfxPort_setPinHigh(&MODULE_P00, 11);   /* LIN4-7 */
    IfxPort_setPinModeOutput(&MODULE_P00, 10, IfxPort_OutputMode_pushPull, IfxPort_OutputIdx_general);
    IfxPort_setPinHigh(&MODULE_P00, 10);   /* LIN8-11 */
}

void lin_xcvr_set_group(uint8 group, uint8 normal)
{
    IfxPort_State st = normal ? IfxPort_State_high : IfxPort_State_low;
    if (group == 0)      IfxPort_setPinState(&MODULE_P02, 8, st);
    else if (group == 1) IfxPort_setPinState(&MODULE_P00, 11, st);
    else if (group == 2) IfxPort_setPinState(&MODULE_P00, 10, st);
}

void lin_xcvr_set_all(uint8 normal)
{
    lin_xcvr_set_group(0, normal);
    lin_xcvr_set_group(1, normal);
    lin_xcvr_set_group(2, normal);
}

/* ---------- PID helpers ---------- */
uint8 lin_pid(uint8 id6)
{
    uint8 id = id6 & 0x3FU;
    uint8 p0 = ((id >> 0) & 1) ^ ((id >> 1) & 1) ^ ((id >> 2) & 1) ^ ((id >> 4) & 1);
    uint8 p1 = ~(((id >> 1) & 1) ^ ((id >> 3) & 1) ^ ((id >> 4) & 1) ^ ((id >> 5) & 1)) & 1;
    return (uint8)(id | (p0 << 6) | (p1 << 7));
}

uint8 lin_id6(uint8 pid)
{
    return pid & 0x3FU;
}

sint8 lin_pid_check(uint8 pid)
{
    return (lin_pid(pid & 0x3FU) == pid) ? 0 : -1;
}

/* ---------- init ---------- */
/* Same set as the proven TC387 uart8lin reference (lin_enable_polling_flags):
 * in polling mode the LIN event flags must be explicitly enabled, otherwise
 * e.g. RHE/RRE never latch and slaves time out. Called after initModule
 * (which leaves FLAGSENABLE=0 in polling mode). */
static void lin_enable_polling_flags(Ifx_ASCLIN *sfr)
{
    IfxAsclin_enableBreakDetectedFlag(sfr, TRUE);
    IfxAsclin_enableCollisionDetectionErrorFlag(sfr, TRUE);
    IfxAsclin_enableFrameErrorFlag(sfr, TRUE);
    IfxAsclin_enableHeaderTimeoutFlag(sfr, TRUE);
    IfxAsclin_enableLinAutoBaudDetectionErrorFlag(sfr, TRUE);
    IfxAsclin_enableLinChecksumErrorFlag(sfr, TRUE);
    IfxAsclin_enableLinParityErrorFlag(sfr, TRUE);
    IfxAsclin_enableResponseTimeoutFlag(sfr, TRUE);
    IfxAsclin_enableRxFifoOverflowFlag(sfr, TRUE);
    IfxAsclin_enableRxHeaderEndFlag(sfr, TRUE);
    IfxAsclin_enableRxResponseEndFlag(sfr, TRUE);
    IfxAsclin_enableTxHeaderEndFlag(sfr, TRUE);
    IfxAsclin_enableTxResponseEndFlag(sfr, TRUE);
    IfxAsclin_enableTxFifoOverflowFlag(sfr, TRUE);
}

static void lin_init_channel(linChannel ch, float32 baud, uint8 isMaster)
{
    IfxAsclin_Lin_Config cfg;

    /* NOTE: no KRST here — a kernel reset hung the boot (RSTSTAT never set,
     * board silent until reflash). ASCLIN init alone is sufficient. */
    /* Match the proven TC387 reference: disable before (re-)init. */
    if (linHandle[ch].asclin != NULL) {
        IfxAsclin_Lin_disableModule(&linHandle[ch]);
    }
    IfxAsclin_Lin_initModuleConfig(&cfg, linSfr[ch]);
    cfg.linMode = isMaster ? IfxAsclin_LinMode_master : IfxAsclin_LinMode_slave;
    cfg.brg.baudrate = baud;
    /* keep iLLD LIN defaults: prescaler 4 / OS16 / 1 sample / SP3,
     * enhanced checksum, HW checksum on, response timeout 255. */
    cfg.brd.abd = FALSE;
    cfg.pins = &linPins[ch];
    /* RxSel (a..g) == ALTI 0..6: derive from the pin struct itself. */
    cfg.alti = (IfxAsclin_RxInputSelect)linPins[ch].rx->select;
    cfg.isInterruptMode = FALSE;
    /* Break: master generates 16 bits (margin over the 13-bit minimum),
     * slaves detect at 11 bits (LIN-compliant window). iLLD 13/13 default
     * proved marginal on this board (TLIN1024 edges + FDR rounding):
     * slaves saw FED/RED but never BD/RHE with a 13-bit master break,
     * while a 14-bit bit-banged break decoded fine. */
    cfg.lin.breakLength = isMaster ? 16 : 11;
    IfxAsclin_Lin_initModule(&linHandle[ch], &cfg);
    lin_enable_polling_flags(linSfr[ch]);

    g_lin[ch].used = 1;
    g_lin[ch].isMaster = isMaster;
}

void lin12_init_all(float32 baud)
{
    linChannel ch;
    if (baud < 1000.0f) baud = 19200.0f;
    g_linBaud = baud;
    memset(g_lin, 0, sizeof(g_lin));
    /* LIN0 intentionally skipped (ASCLIN0 = UART0 debug console).
     * Default masters: LIN3 (bus A: 1-2-3), LIN7 (bus B: 4-5-6-7),
     * LIN11 (bus C: 8-9-10-11); all others slave. */
    for (ch = LIN1; ch < LIN_NUM; ch++) {
        uint8 isMaster = (ch == LIN3 || ch == LIN7 || ch == LIN_MASTER_CH) ? 1 : 0;
        lin_init_channel(ch, baud, isMaster);
    }
}

void lin12_init_all_19200(void)
{
    lin12_init_all(19200.0f);
}


/* ---------- timeout-guarded primitives ---------- */
#define LIN_HDR_TIMEOUT_MS   50u
#define LIN_RESP_TIMEOUT_MS  100u

static uint32 lin_elapsed(uint32 t0);
static int lin_tx_header(Ifx_ASCLIN *sfr, uint8 pid, linChState_t *st);
static int lin_tx_response(Ifx_ASCLIN *sfr, const uint8 *data, uint8 len,
                           uint8 classic, linChState_t *st);
static void lin_arm_header(Ifx_ASCLIN *sfr);
static int lin_poll_header(Ifx_ASCLIN *sfr, uint8 *pid, linChState_t *st);
static void lin_arm_response(Ifx_ASCLIN *sfr, uint8 len, uint8 classic);
static int lin_poll_response(Ifx_ASCLIN *sfr, uint8 *data, uint8 len,
                             linChState_t *st);

static uint32 lin_elapsed(uint32 t0)
{
    return g_TickCount_1ms - t0;
}

/* Master/slave header TX (master role): write PID, request header, poll THE. */
static int lin_tx_header(Ifx_ASCLIN *sfr, uint8 pid, linChState_t *st)
{
    uint32 t0;
    uint8 b = pid;
    IfxAsclin_clearAllFlags(sfr);
    IfxAsclin_enableRxFifoInlet(sfr, FALSE);
    IfxAsclin_flushTxFifo(sfr);
    IfxAsclin_enableTxFifoOutlet(sfr, TRUE);
    IfxAsclin_write8(sfr, &b, 1U);
    IfxAsclin_setTransmitHeaderRequestFlag(sfr);
    t0 = g_TickCount_1ms;
    while (!IfxAsclin_getTxHeaderEndFlagStatus(sfr)) {
        if (IfxAsclin_getHeaderTimeoutFlagStatus(sfr) ||
            IfxAsclin_getLinParityErrorFlagStatus(sfr) ||
            IfxAsclin_getFrameErrorFlagStatus(sfr) ||
            IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr)) {
            break;
        }
        if (lin_elapsed(t0) > LIN_HDR_TIMEOUT_MS) break;
    }
    if (IfxAsclin_getTxHeaderEndFlagStatus(sfr)) {
        IfxAsclin_clearTxHeaderEndFlag(sfr);
        if (st) st->txHdr++;
        return 0;
    }
    /* classify */
    if (st) {
        st->hdrErr++;
        if (IfxAsclin_getHeaderTimeoutFlagStatus(sfr)) st->timeoutErr++;
        if (IfxAsclin_getLinParityErrorFlagStatus(sfr)) st->parityErr++;
        if (IfxAsclin_getFrameErrorFlagStatus(sfr) ||
            IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr)) st->frameErr++;
        if (!IfxAsclin_getHeaderTimeoutFlagStatus(sfr) &&
            !IfxAsclin_getLinParityErrorFlagStatus(sfr) &&
            !IfxAsclin_getFrameErrorFlagStatus(sfr) &&
            !IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr)) st->timeoutErr++;
    }
    IfxAsclin_clearAllFlags(sfr);
    return -1;
}

/* Response TX (either role): DATLEN + checksum mode, write data, poll TRE. */
static int lin_tx_response(Ifx_ASCLIN *sfr, const uint8 *data, uint8 len,
                           uint8 classic, linChState_t *st)
{
    uint32 t0;
    if (len < 1) len = 1;
    if (len > 8) len = 8;
    IfxAsclin_setDataLength(sfr, (IfxAsclin_DataLength)(len - 1));
    IfxAsclin_setChecksumMode(sfr, classic ? IfxAsclin_Checksum_classic : IfxAsclin_Checksum_enhanced);
    IfxAsclin_clearAllFlags(sfr);
    IfxAsclin_flushTxFifo(sfr);
    IfxAsclin_enableRxFifoInlet(sfr, FALSE);
    IfxAsclin_enableTxFifoOutlet(sfr, TRUE);
    IfxAsclin_write8(sfr, (uint8 *)data, len);
    IfxAsclin_setTransmitResponseRequestFlag(sfr);
    t0 = g_TickCount_1ms;
    while (!IfxAsclin_getTxResponseEndFlagStatus(sfr)) {
        if (IfxAsclin_getResponseTimeoutFlagStatus(sfr) ||
            IfxAsclin_getTxFifoOverflowFlagStatus(sfr) ||
            IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr) ||
            IfxAsclin_getBreakDetectedFlagStatus(sfr)) {
            break;
        }
        if (lin_elapsed(t0) > LIN_RESP_TIMEOUT_MS) break;
    }
    if (IfxAsclin_getTxResponseEndFlagStatus(sfr)) {
        IfxAsclin_clearTxResponseEndFlag(sfr);
        if (st) st->txResp++;
        return 0;
    }
    if (st) {
        st->respErr++;
        if (IfxAsclin_getResponseTimeoutFlagStatus(sfr)) st->timeoutErr++;
        else if (IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr) ||
                 IfxAsclin_getBreakDetectedFlagStatus(sfr) ||
                 IfxAsclin_getTxFifoOverflowFlagStatus(sfr)) st->frameErr++;
        else st->timeoutErr++;
    }
    IfxAsclin_clearAllFlags(sfr);
    return -1;
}

/* Arm header RX (either role): mirror of IfxAsclin_Lin_prepareHeaderReception. */
static void lin_arm_header(Ifx_ASCLIN *sfr)
{
    IfxAsclin_clearAllFlags(sfr);
    IfxAsclin_flushRxFifo(sfr);
    IfxAsclin_enableTxFifoOutlet(sfr, FALSE);
    IfxAsclin_enableRxFifoInlet(sfr, TRUE);
}

/* Poll header RX with timeout. Returns 0 + pid on success. */
static int lin_poll_header(Ifx_ASCLIN *sfr, uint8 *pid, linChState_t *st)
{
    uint32 t0 = g_TickCount_1ms;
    while (!IfxAsclin_getRxHeaderEndFlagStatus(sfr)) {
        if (IfxAsclin_getHeaderTimeoutFlagStatus(sfr) ||
            IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr) ||
            IfxAsclin_getFrameErrorFlagStatus(sfr) ||
            IfxAsclin_getLinAutoBaudDetectionErrorFlagStatus(sfr) ||
            IfxAsclin_getLinParityErrorFlagStatus(sfr)) {
            break;
        }
        if (lin_elapsed(t0) > LIN_HDR_TIMEOUT_MS) break;
    }
    if (IfxAsclin_getRxHeaderEndFlagStatus(sfr)) {
        uint8 b = 0;
        IfxAsclin_clearRxHeaderEndFlag(sfr);
        IfxAsclin_read8(sfr, &b, 1U);
        if (pid) *pid = b;
        if (st) st->rxHdr++;
        if (st && IfxAsclin_getLinParityErrorFlagStatus(sfr)) {
            /* latched alongside RHE on some revisions: count, keep frame */
            st->parityErr++;
        }
        return 0;
    }
    if (st) {
        st->hdrErr++;
        if (IfxAsclin_getHeaderTimeoutFlagStatus(sfr)) st->timeoutErr++;
        else if (IfxAsclin_getLinParityErrorFlagStatus(sfr)) st->parityErr++;
        else if (IfxAsclin_getFrameErrorFlagStatus(sfr) ||
                 IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr)) st->frameErr++;
        else st->timeoutErr++;
    }
    IfxAsclin_clearAllFlags(sfr);
    return -1;
}

/* Arm response RX: mirror of IfxAsclin_Lin_prepareResponseReception. */
static void lin_arm_response(Ifx_ASCLIN *sfr, uint8 len, uint8 classic)
{
    if (len < 1) len = 1;
    if (len > 8) len = 8;
    IfxAsclin_setDataLength(sfr, (IfxAsclin_DataLength)(len - 1));
    IfxAsclin_setChecksumMode(sfr, classic ? IfxAsclin_Checksum_classic : IfxAsclin_Checksum_enhanced);
    IfxAsclin_clearAllFlags(sfr);
    IfxAsclin_flushRxFifo(sfr);
    IfxAsclin_enableTxFifoOutlet(sfr, FALSE);
    IfxAsclin_enableRxFifoInlet(sfr, TRUE);
}

/* Poll response RX with timeout. Returns 0 + data on success. */
static int lin_poll_response(Ifx_ASCLIN *sfr, uint8 *data, uint8 len,
                             linChState_t *st)
{
    uint32 t0 = g_TickCount_1ms;
    if (len < 1) len = 1;
    if (len > 8) len = 8;
    while (!IfxAsclin_getRxResponseEndFlagStatus(sfr)) {
        if (IfxAsclin_getRxFifoOverflowFlagStatus(sfr) ||
            IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr) ||
            IfxAsclin_getFrameErrorFlagStatus(sfr) ||
            IfxAsclin_getLinChecksumErrorFlagStatus(sfr) ||
            IfxAsclin_getResponseTimeoutFlagStatus(sfr) ||
            IfxAsclin_getBreakDetectedFlagStatus(sfr)) {
            break;
        }
        if (lin_elapsed(t0) > LIN_RESP_TIMEOUT_MS) break;
    }
    if (IfxAsclin_getRxResponseEndFlagStatus(sfr)) {
        IfxAsclin_clearRxResponseEndFlag(sfr);
        IfxAsclin_read8(sfr, data, len);
        if (st) st->rxResp++;
        return 0;
    }
    if (st) {
        st->respErr++;
        if (IfxAsclin_getLinChecksumErrorFlagStatus(sfr)) st->cksumErr++;
        else if (IfxAsclin_getResponseTimeoutFlagStatus(sfr)) st->timeoutErr++;
        else if (IfxAsclin_getFrameErrorFlagStatus(sfr) ||
                 IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr) ||
                 IfxAsclin_getRxFifoOverflowFlagStatus(sfr)) st->frameErr++;
        else st->timeoutErr++;
    }
    IfxAsclin_clearAllFlags(sfr);
    return -1;
}

int lin_set_role(linChannel ch, uint8 isMaster)
{
    if (ch < LIN1 || ch > LIN11) return -1;
    lin_init_channel(ch, g_linBaud, isMaster ? 1 : 0);
    return 0;
}

void lin_all_slave(void)
{
    linChannel ch;
    for (ch = LIN1; ch <= LIN11; ch++) {
        lin_init_channel(ch, g_linBaud, 0);
    }
}

/* External-master sniff: all LIN1..LIN11 listen for one header+response.
 * Raw-monitor style (mirrors the proven TC387 uart8lin reference which
 * passed full-receive tests): the response is captured with DATLEN=9 and
 * HW checksum OFF, so no length/checksum assumption is needed; the payload
 * is validated by the caller against the known analyzer frames.
 * Timing: header and response arrive back-to-back from the external master,
 * so after the first RHE latch we do exactly one more full scan pass (catch
 * late latchers on the same bus, ~us apart) and immediately arm responses.
 * No extra ms-scale wait: that would miss the response already on the bus. */
uint8 lin_checksum(uint8 pid, const uint8 *data, uint8 len, uint8 classic)
{
    uint32 sum = 0;
    uint8 i;
    if (!classic) sum += pid;
    for (i = 0; i < len; i++) sum += data[i];
    while (sum > 255u) sum -= 255u;
    return (uint8)(~sum & 0xFFu);
}

/* Normal slave response registers (iLLD defaults, also used by pairwise). */
static void lin_apply_normal_response(Ifx_ASCLIN *sfr)
{
    IfxAsclin_setChecksumInjection(sfr, IfxAsclin_ChecksumInjection_written);
    IfxAsclin_enableHardwareChecksum(sfr, TRUE);
    IfxAsclin_setLinResponseTimeoutMode(sfr, IfxAsclin_LinResponseTimeoutMode_frameTimeout);
    IfxAsclin_setLinResponseTimeoutThreshold(sfr, 255U);
    IfxAsclin_setHeaderResponseSelect(sfr, IfxAsclin_HeaderResponseSelect_headerAndResponse);
}

/* Raw-monitor response registers (TC387 uart8lin reference). */
static void lin_apply_raw_response(Ifx_ASCLIN *sfr)
{
    IfxAsclin_setChecksumInjection(sfr, IfxAsclin_ChecksumInjection_written);
    IfxAsclin_enableHardwareChecksum(sfr, FALSE);
    IfxAsclin_setDataLength(sfr, IfxAsclin_DataLength_9);
    IfxAsclin_setLinResponseTimeoutMode(sfr, IfxAsclin_LinResponseTimeoutMode_responseTimeout);
    IfxAsclin_setLinResponseTimeoutThreshold(sfr, 128U);
}

int lin_sniff_ext_frame(uint8 *pidOut, uint8 *expLen, uint8 *classicUsed,
                        uint32 *hdrMask, uint32 *respMask,
                        uint8 data[LIN_NUM][10], uint8 rawLen[LIN_NUM],
                        uint32 timeoutMs)
{
    linChannel ch;
    uint32 t0, hdr = 0, done = 0, okm = 0;
    uint8 pids[LIN_NUM];
    uint8 pidFirst = 0, firstSeen = 0;
    uint8 id6 = 0, exp = 8, classic = 0, expRaw = 9;
    uint8 acc[LIN_NUM][10];
    uint8 accN[LIN_NUM];
    int i;

    if (timeoutMs < 500u) timeoutMs = 500u;
    if (timeoutMs > 10000u) timeoutMs = 10000u;
    memset(pids, 0, sizeof(pids));
    memset(acc, 0, sizeof(acc));
    memset(accN, 0, sizeof(accN));
    if (data) memset(data, 0, LIN_NUM * 10u);
    if (rawLen) memset(rawLen, 0, LIN_NUM);

    /* 1) normal registers + arm all for header */
    for (ch = LIN1; ch <= LIN11; ch++) {
        lin_apply_normal_response(linSfr[ch]);
        lin_arm_header(linSfr[ch]);
    }

    /* 2) wait for external header (RHE latches per channel, poll round-robin) */
    t0 = g_TickCount_1ms;
    while ((g_TickCount_1ms - t0) < timeoutMs) {
        for (ch = LIN1; ch <= LIN11; ch++) {
            Ifx_ASCLIN *sfr;
            if (hdr & (1u << ch)) continue;
            sfr = linSfr[ch];
            if (IfxAsclin_getRxHeaderEndFlagStatus(sfr)) {
                uint8 b = 0;
                IfxAsclin_clearRxHeaderEndFlag(sfr);
                IfxAsclin_read8(sfr, &b, 1U);
                pids[ch] = b;
                hdr |= (1u << ch);
                g_lin[ch].rxHdr++;
                if (IfxAsclin_getLinParityErrorFlagStatus(sfr)) g_lin[ch].parityErr++;
                if (!firstSeen) { pidFirst = b; firstSeen = 1; }
                IfxAsclin_clearAllFlags(sfr);
            } else if (IfxAsclin_getHeaderTimeoutFlagStatus(sfr) ||
                       IfxAsclin_getFrameErrorFlagStatus(sfr) ||
                       IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr) ||
                       IfxAsclin_getLinParityErrorFlagStatus(sfr)) {
                /* header error latched before RHE: count once, re-arm so a
                 * later frame in the same window can still be caught */
                g_lin[ch].hdrErr++;
                if (IfxAsclin_getLinParityErrorFlagStatus(sfr)) g_lin[ch].parityErr++;
                else if (IfxAsclin_getHeaderTimeoutFlagStatus(sfr)) g_lin[ch].timeoutErr++;
                else g_lin[ch].frameErr++;
                IfxAsclin_clearAllFlags(sfr);
                lin_arm_header(sfr);
            }
        }
        if (hdr) break; /* first pass with any hit: one more pass below */
    }
    if (!hdr) {
        if (hdrMask) *hdrMask = 0;
        if (respMask) *respMask = 0;
        return -1;
    }
    /* one more scan pass for same-bus late latchers (no ms wait) */
    for (ch = LIN1; ch <= LIN11; ch++) {
        Ifx_ASCLIN *sfr;
        if (hdr & (1u << ch)) continue;
        sfr = linSfr[ch];
        if (IfxAsclin_getRxHeaderEndFlagStatus(sfr)) {
            uint8 b = 0;
            IfxAsclin_clearRxHeaderEndFlag(sfr);
            IfxAsclin_read8(sfr, &b, 1U);
            pids[ch] = b;
            hdr |= (1u << ch);
            g_lin[ch].rxHdr++;
            if (IfxAsclin_getLinParityErrorFlagStatus(sfr)) g_lin[ch].parityErr++;
            IfxAsclin_clearAllFlags(sfr);
        }
    }

    /* 3) expected payload from first PID */
    id6 = pidFirst & 0x3FU;
    if (id6 == 0x17) { exp = 2; classic = 1; expRaw = 3; }
    else if (id6 == 0x31) { exp = 8; classic = 0; expRaw = 9; }
    else if (id6 >= 0x3C) { exp = 8; classic = 1; expRaw = 9; }
    else { exp = 8; classic = 0; expRaw = 9; }
    if (pidOut) *pidOut = pidFirst;
    if (expLen) *expLen = exp;
    if (classicUsed) *classicUsed = classic;
    if (hdrMask) *hdrMask = hdr;

    /* 4) arm header-hit channels for raw response capture */
    for (ch = LIN1; ch <= LIN11; ch++) {
        Ifx_ASCLIN *sfr;
        if (!(hdr & (1u << ch))) continue;
        sfr = linSfr[ch];
        lin_apply_raw_response(sfr);
        IfxAsclin_clearAllFlags(sfr);
        IfxAsclin_flushRxFifo(sfr);
        IfxAsclin_enableTxFifoOutlet(sfr, FALSE);
        IfxAsclin_enableRxFifoInlet(sfr, TRUE);
    }

    /* 5) capture: drain FIFO continuously, finish per channel on RRE (full
     * 9B), RT (short frame done, e.g. 2B+CK), or bus error / next break. */
    t0 = g_TickCount_1ms;
    while ((g_TickCount_1ms - t0) < 500u) {
        for (ch = LIN1; ch <= LIN11; ch++) {
            Ifx_ASCLIN *sfr;
            uint8 n;
            if (!(hdr & (1u << ch))) continue;
            if (done & (1u << ch)) continue;
            sfr = linSfr[ch];
            /* drain whatever arrived */
            for (;;) {
                n = IfxAsclin_getRxFifoFillLevel(sfr);
                if (n == 0) break;
                if (n > 10u) n = 10u;
                {
                    uint8 tmp[10];
                    uint8 k, take;
                    if (n > 10u) n = 10u;
                    IfxAsclin_read8(sfr, tmp, n);
                    take = (uint8)(10u - accN[ch]);
                    if (take > n) take = n;
                    for (k = 0; k < take; k++) acc[ch][accN[ch] + k] = tmp[k];
                    accN[ch] = (uint8)(accN[ch] + take);
                }
            }
            if (IfxAsclin_getRxResponseEndFlagStatus(sfr) ||
                IfxAsclin_getResponseTimeoutFlagStatus(sfr) ||
                IfxAsclin_getFrameErrorFlagStatus(sfr) ||
                IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr) ||
                IfxAsclin_getRxFifoOverflowFlagStatus(sfr) ||
                IfxAsclin_getBreakDetectedFlagStatus(sfr)) {
                /* one final drain after the end flag */
                for (;;) {
                    n = IfxAsclin_getRxFifoFillLevel(sfr);
                    if (n == 0) break;
                    if (n > 10u) n = 10u;
                    {
                        uint8 tmp[10];
                        uint8 k, take;
                        IfxAsclin_read8(sfr, tmp, n);
                        take = (uint8)(10u - accN[ch]);
                        if (take > n) take = n;
                        for (k = 0; k < take; k++) acc[ch][accN[ch] + k] = tmp[k];
                        accN[ch] = (uint8)(accN[ch] + take);
                    }
                }
                if (IfxAsclin_getFrameErrorFlagStatus(sfr) ||
                    IfxAsclin_getCollisionDetectionErrorFlagStatus(sfr) ||
                    IfxAsclin_getRxFifoOverflowFlagStatus(sfr)) {
                    g_lin[ch].respErr++;
                    g_lin[ch].frameErr++;
                    g_lin[ch].lastOk = 0;
                } else {
                    /* RRE / RT / next-break: captured bytes are the frame */
                    g_lin[ch].rxResp++;
                    if (accN[ch] == expRaw) {
                        okm |= (1u << ch);
                        g_lin[ch].lastId = id6;
                        g_lin[ch].lastLen = (exp > 8) ? 8 : exp;
                        for (i = 0; i < g_lin[ch].lastLen; i++) {
                            g_lin[ch].lastData[i] = acc[ch][i];
                        }
                        g_lin[ch].lastClassic = classic ? 1 : 0;
                        g_lin[ch].lastDir = 0;
                        g_lin[ch].lastTick = g_TickCount_1ms;
                        g_lin[ch].lastOk = 1;
                    } else {
                        g_lin[ch].respErr++;
                        g_lin[ch].timeoutErr++;
                        g_lin[ch].lastOk = 0;
                    }
                    if (IfxAsclin_getLinChecksumErrorFlagStatus(sfr)) {
                        /* HW checksum is OFF in raw mode; ignore if set */
                    }
                }
                IfxAsclin_clearAllFlags(sfr);
                done |= (1u << ch);
            }
        }
        if ((done & hdr) == hdr) break;
    }
    /* still pending -> timeout */
    for (ch = LIN1; ch <= LIN11; ch++) {
        if ((hdr & (1u << ch)) && !(done & (1u << ch))) {
            g_lin[ch].respErr++;
            g_lin[ch].timeoutErr++;
            g_lin[ch].lastOk = 0;
            IfxAsclin_clearAllFlags(linSfr[ch]);
            done |= (1u << ch);
        }
        /* restore normal registers for the next command */
        if (hdr & (1u << ch)) lin_apply_normal_response(linSfr[ch]);
        if (rawLen) rawLen[ch] = accN[ch];
        if (data) for (i = 0; i < 10; i++) data[ch][i] = acc[ch][i];
    }
    if (respMask) *respMask = okm;
    if (okm) return 0;
    return -2;
}

/* Pairwise master -> slave (header + response from master, slave verifies). */
int lin_xact_m2s(linChannel master, linChannel slave, uint8 id6,
                 const uint8 *data, uint8 len, uint8 classic)
{
    uint8 pid = lin_pid(id6);
    uint8 rxPid = 0, rxData[8];
    int i;

    if (master < LIN1 || master > LIN11 || slave < LIN1 || slave > LIN11) return -1;
    if (len < 1) len = 1;
    if (len > 8) len = 8;

    lin_arm_header(linSfr[slave]);
    if (lin_tx_header(linSfr[master], pid, &g_lin[master]) != 0) return -1;
    if (lin_poll_header(linSfr[slave], &rxPid, &g_lin[slave]) != 0 || rxPid != pid) return -1;
    lin_arm_response(linSfr[slave], len, classic);
    if (lin_tx_response(linSfr[master], data, len, classic, &g_lin[master]) != 0) {
        g_lin[slave].respErr++;
        return -1;
    }
    memset(rxData, 0, sizeof(rxData));
    if (lin_poll_response(linSfr[slave], rxData, len, &g_lin[slave]) != 0) return -1;
    for (i = 0; i < len; i++) {
        if (rxData[i] != data[i]) {
            g_lin[slave].respErr++;
            return -1;
        }
    }
    g_lin[slave].lastId = id6 & 0x3FU;
    g_lin[slave].lastLen = len;
    for (i = 0; i < len; i++) g_lin[slave].lastData[i] = rxData[i];
    g_lin[slave].lastClassic = classic ? 1 : 0;
    g_lin[slave].lastDir = 0;
    g_lin[slave].lastTick = g_TickCount_1ms;
    g_lin[slave].lastOk = 1;
    g_lin[master].lastId = id6 & 0x3FU;
    g_lin[master].lastLen = len;
    for (i = 0; i < len; i++) g_lin[master].lastData[i] = data[i];
    g_lin[master].lastClassic = classic ? 1 : 0;
    g_lin[master].lastDir = 0;
    g_lin[master].lastTick = g_TickCount_1ms;
    g_lin[master].lastOk = 1;
    return 0;
}


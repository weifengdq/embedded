/* lin12.c — TC397 LIN x11 driver (ASCLIN LIN, polling, single-core).
 *
 * Design notes:
 * - iLLD IfxAsclin_Lin blocking APIs (receiveHeader/receiveResponse/...) loop
 *   forever until HW flags arrive, so they cannot be used for multi-node
 *   scripted tests on one core (master TX while slaves RX would deadlock).
 *   This driver therefore implements its own tick-timeout guarded primitives
 *   on top of the IfxAsclin_* flag helpers, mirroring the iLLD sequences.
 * - Transactions are master-driven and fully synchronous: arm slaves ->
 *   master header -> slaves check header -> arm slaves for response ->
 *   response TX -> receivers check response. Gaps are sub-ms, well inside
 *   the LIN response-space / response-timeout window (DATCON.RESPONSE=255).
 * - Chemistry: PID parity is generated by lin_pid(); HW checks parity on RX
 *   (LP flag) and checksum on response RX (LC flag, enhanced by default).
 */

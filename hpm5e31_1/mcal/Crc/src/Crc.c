/* ============================== 扩展 API ============================== */
void Crc_Init(void)
{
    crc_hw_ensure_ready();
}

void Crc_SetHwEnabled(boolean enable)
{
    s_hwEnable = (enable != FALSE) ? TRUE : FALSE;
    if (s_hwEnable) {
        crc_hw_ensure_ready();
    }
}

boolean Crc_IsHwActive(Crc_AlgoType algo)
{
    if (algo >= CRC_ALGO_COUNT) {
        return FALSE;
    }
    crc_hw_ensure_ready();
    return ((s_hwEnable) && ((s_hwWholeConv[algo].ok != 0U) || (s_hwChainConv[algo].ok != 0U)))
           ? TRUE : FALSE;
}

uint64 Crc_CalculateByAlgo(Crc_AlgoType algo, const uint8 *data, uint32 length,
                           uint64 startValue, boolean isFirstCall)
{
    if (algo >= CRC_ALGO_COUNT) {
        return 0ULL;
    }
    return crc_calc(algo, data, length, crc_start_reg(algo, startValue, isFirstCall),
                    (boolean)(isFirstCall == FALSE));
}

uint32 Crc_GetHwConv(Crc_AlgoType algo, uint32 *convMask)
{
    if ((algo >= CRC_ALGO_COUNT) || (convMask == NULL_PTR)) {
        return 1U;
    }
    crc_hw_ensure_ready();
    *convMask = (uint32)s_hwWholeConv[algo].ok
              | ((uint32)s_hwWholeConv[algo].initRefl << 1)
              | ((uint32)s_hwWholeConv[algo].xorInSw << 2)
              | ((uint32)s_hwWholeConv[algo].feedWord << 3)
              | ((uint32)s_hwWholeConv[algo].polyShift << 4)
              | ((uint32)s_hwChainConv[algo].ok << 8);
    return (s_hwWholeConv[algo].ok != 0U) ? 0U : 1U;
}

uint32 Crc_GetHwStats(uint32 *hwCalls, uint32 *swFallbacks)
{
    if (hwCalls != NULL_PTR) {
        *hwCalls = s_hwCalls;
    }
    if (swFallbacks != NULL_PTR) {
        *swFallbacks = s_swFallbacks;
    }
    return 0U;
}

/* 诊断：用 SDK 已验证的 preset 路径做一次原始探测，用于排查外设/时钟/寄存器约定问题。
 * variant 0: crc_preset_crc32（init/xorout/refin/refout 全由 preset 给），期望 0xCECEE288
 * variant 1: 自定义参数（与 preset 等价）
 * 返回 RESULT 原值；out* 回读 PRE_SET/MISC_SETTING 便于看配置是否落地。 */
uint32 Crc_HwRawProbe(uint32 variant, uint32 *outPreSet, uint32 *outMisc)
{
    static const uint8 probe[16] = {0U, 1U, 2U, 3U, 4U, 5U, 6U, 7U, 8U, 9U, 10U, 11U, 12U, 13U, 14U, 15U};
    static const uint8 pattern[16] = {
        0x00U, 0x11U, 0x22U, 0x33U, 0x44U, 0x55U, 0x66U, 0x77U,
        0x88U, 0x99U, 0xAAU, 0xBBU, 0xCCU, 0xDDU, 0xEEU, 0xFFU
    };
    crc_channel_config_t cfg;
    const uint8 *buf = probe;
    uint8 ch = 0U;

    crc_hw_ensure_ready();
    if (s_crc == NULL_PTR) {
        return 0xDEADBEEFUL;
    }
    s_crc->CHN[ch].CLR = 1U;
    cfg.preset = crc_preset_none;
    cfg.in_byte_order = crc_in_byte_order_lsb;
    cfg.init = 0xFFFFFFFFUL;
    cfg.poly = 0x04C11DB7UL;
    cfg.poly_width = CRC_POLY_WIDTH_32;
    cfg.refout = crc_refout_true;
    cfg.refin = crc_refin_true;
    cfg.xorout = 0xFFFFFFFFUL;

    if (variant == 0U) {
        cfg.preset = crc_preset_crc32;
    } else if ((variant == 2U) || (variant == 4U)) {
        buf = pattern;   /* 与校准同一组数据 */
    } else if ((variant == 3U) || (variant == 5U)) {
        /* CRC8 探测：poly 0x1D, width 8, init/xorout 0xFF, 不反射 */
        cfg.init = 0x000000FFUL;
        cfg.poly = 0x0000001DUL;
        cfg.poly_width = CRC_POLY_WIDTH_8;
        cfg.refout = crc_refout_false;
        cfg.refin = crc_refin_false;
        cfg.xorout = 0x000000FFUL;
        if (variant == 5U) {
            buf = pattern;
        }
    } else if (variant == 6U) {
        /* CRC8 探测：poly 左对齐到 32 位 */
        cfg.init = 0x000000FFUL;
        cfg.poly = 0x1D000000UL;
        cfg.poly_width = CRC_POLY_WIDTH_8;
        cfg.refout = crc_refout_false;
        cfg.refin = crc_refin_false;
        cfg.xorout = 0x000000FFUL;
    }
    (void)crc_setup_channel_config(s_crc, ch, &cfg);
    crc_calc_block_bytes(s_crc, ch, (uint8_t *)(void *)buf, 16U);
    if (outPreSet != NULL_PTR) { *outPreSet = s_crc->CHN[ch].PRE_SET; }
    if (outMisc != NULL_PTR) { *outMisc = s_crc->CHN[ch].MISC_SETTING; }
    return crc_get_result(s_crc, ch);
}

const char *Crc_GetAlgoName(Crc_AlgoType algo)
{
    static const char *const names[CRC_ALGO_COUNT] = {
        "CRC8 SAE J1850", "CRC8 H2F", "CRC16 CCITT-FALSE", "CRC16 ARC(0x8005)",
        "CRC32 Ethernet", "CRC32 P4(0xF4ACFB13)", "CRC32 P76(0x6938392D)", "CRC64 ECMA-182"
    };
    if (algo >= CRC_ALGO_COUNT) {
        return "?";
    }
    return names[algo];
}


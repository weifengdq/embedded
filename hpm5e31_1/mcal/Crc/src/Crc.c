/*
 * Crc.c —— AUTOSAR CRC Library 实现（HPM5E31，CRC 外设加速 + 软件表对照）
 *
 * 依据：AUTOSAR_CP_SWS_CRCLibrary R25-11
 *       §7.2.x 各多项式的 poly/init/refin/refout/xorout 与标准校验值
 *       §8.3   八个 Crc_Calculate* 的语义（Crc_IsFirstCall 的两种分支）
 *       [SWS_Crc_00014] 首次调用：Crc=Init；[SWS_Crc_00041] 后续调用：Crc=StartValue⊕XOR
 *       [SWS_Crc_00072] CRC 库函数不得调用任何 BSW 模块（因此无 Det 调用）
 * 硬件：hpm_sdk/drivers/src/hpm_crc_drv.c（8 通道，自定义 poly/init/refin/refout/xorout，
 *       poly 宽度 4~32 位；>16 字节时可用 crc_calc_large_block_fast 按字喂数）。
 * 例程：samples/mcal/crc_bench、samples/mcal/crc_integrity。
 *
 * 实现策略：
 *  1) 软件路径：8 张 256 项查表（合计 6656 B Flash），逐字节运算，作为"金标准"；
 *  2) 硬件路径：≤32 位的 7 个算法走 CRC 外设（CRC64 位宽超出外设能力，只能软件）；
 *  3) 上电自校准：硬件寄存器约定（init 是否需按位反序、xorout 由硬件还是软件加）没有
 *     文档化，故首次使用时用"标准向量 + 分段链式"两种输入与软件结果比对，自动选定
 *     约定；4 种组合都对不上则该算法永久回落软件（bench 会打印实际选中的组合）。
 */

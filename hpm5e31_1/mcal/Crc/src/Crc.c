/* ============================== 硬件状态与寄存器约定 ============================== */
/* 外设的 init/xorout/poly 对齐/喂数方式没有在 RM 里写清，且不同位宽下行为不同，
 * 故为每个算法、每条路径（整段 / 链式）各标定一组约定。 */
typedef struct
{
    uint8 ok;          /* 1 = 该算法在该路径上硬件结果与软件表一致 */
    uint8 initRefl;    /* 1 = init 需按位反序后再写 INIT_DATA */
    uint8 xorInSw;     /* 1 = 外设 XOROUT 置 0，xorout 由软件补加 */
    uint8 feedWord;    /* 1 = 按 32 位字喂数（快）；0 = 按字节喂 */
    uint8 polyShift;   /* 1 = poly 需左对齐到 32 位 */
} crc_hw_conv_t;

static boolean s_hwReady = FALSE;                      /* 时钟/自校准是否已做 */
static boolean s_hwEnable = (CRC_USE_HW_ACCEL == STD_ON) ? TRUE : FALSE;
static CRC_Type *s_crc = NULL_PTR;
static uint8  s_hwChannel = 0U;
static crc_hw_conv_t s_hwWholeConv[CRC_ALGO_COUNT];    /* 首次调用（整段）用的约定 */
static crc_hw_conv_t s_hwChainConv[CRC_ALGO_COUNT];    /* 链式调用（start value 续算）用的约定 */
static uint32 s_hwCalls = 0U;
static uint32 s_swFallbacks = 0U;

/* ============================== 位工具 ============================== */
static uint64 crc_mask(uint8 width)
{
    if (width >= 64U) {
        return 0xFFFFFFFFFFFFFFFFULL;
    }
    return ((uint64)1U << width) - 1ULL;
}

static uint64 crc_bitrev(uint64 v, uint8 width)
{
    uint64 r = 0ULL;
    uint8 i;
    for (i = 0U; i < width; i++) {
        r = (r << 1) | ((v >> i) & 1ULL);
    }
    return r & crc_mask(width);
}

/* CRC64 的 init/xorout 是 64 位，参数表里只放 32 位，这里补完整值 */
static uint64 crc_init_of(Crc_AlgoType algo)
{
    return (algo == CRC_ALGO_CRC64) ? 0xFFFFFFFFFFFFFFFFULL : (uint64)s_algoParam[algo].init;
}

static uint64 crc_xorout_of(Crc_AlgoType algo)
{
    return (algo == CRC_ALGO_CRC64) ? 0xFFFFFFFFFFFFFFFFULL : (uint64)s_algoParam[algo].xorout;
}

/* ============================== 软件实现 ============================== */
static uint64 crc_sw_reg_update(Crc_AlgoType algo, uint64 reg, const uint8 *data, uint32 len)
{
    uint32 i;

    switch (algo) {
    case CRC_ALGO_CRC8:
    {
        uint8 r = (uint8)reg;
        for (i = 0U; i < len; i++) {
            r = s_crc8J1850Table[(uint8)(r ^ data[i])];
        }
        return (uint64)r;
    }
    case CRC_ALGO_CRC8H2F:
    {
        uint8 r = (uint8)reg;
        for (i = 0U; i < len; i++) {
            r = s_crc8H2fTable[(uint8)(r ^ data[i])];
        }
        return (uint64)r;
    }
    case CRC_ALGO_CRC16:
    {
        uint16 r = (uint16)reg;
        for (i = 0U; i < len; i++) {
            r = (uint16)(((uint16)(r << 8)) ^ s_crc16CcittTable[(uint8)((r >> 8) ^ data[i])]);
        }
        return (uint64)r;
    }
    case CRC_ALGO_CRC16ARC:
    {
        uint16 r = (uint16)reg;
        for (i = 0U; i < len; i++) {
            r = (uint16)((r >> 8) ^ s_crc16ArcTable[(uint8)(r ^ data[i])]);
        }
        return (uint64)r;
    }
    case CRC_ALGO_CRC32:
    {
        uint32 r = (uint32)reg;
        for (i = 0U; i < len; i++) {
            r = (r >> 8) ^ s_crc32EthernetTable[(uint8)(r ^ data[i])];
        }
        return (uint64)r;
    }
    case CRC_ALGO_CRC32P4:
    {
        uint32 r = (uint32)reg;
        for (i = 0U; i < len; i++) {
            r = (r >> 8) ^ s_crc32P4Table[(uint8)(r ^ data[i])];
        }
        return (uint64)r;
    }
    case CRC_ALGO_CRC32P76:
    {
        uint32 r = (uint32)reg;
        for (i = 0U; i < len; i++) {
            r = (r << 8) ^ s_crc32P76Table[(uint8)((r >> 24) ^ data[i])];
        }
        return (uint64)r;
    }
    case CRC_ALGO_CRC64:
    {
        uint64 r = reg;
        for (i = 0U; i < len; i++) {
            r = (r >> 8) ^ s_crc64EcmaTable[(uint8)(r ^ data[i])];
        }
        return r;
    }
    default:
        return reg;
    }
}

/* 链式初始寄存器：首次用 init，后续用 StartValue ⊕ XORout（[SWS_Crc_00041]）。
 * 注意：本实现的寄存器是"结果约定"下的值，反射算法不需要再手工 bitrev。 */
static uint64 crc_start_reg(Crc_AlgoType algo, uint64 startValue, boolean isFirstCall)
{
    const crc_algo_param_t *p = &s_algoParam[algo];
    if (isFirstCall) {
        return crc_init_of(algo);
    }
    return (startValue ^ crc_xorout_of(algo)) & crc_mask(p->width);
}

/* ============================== 硬件路径 ============================== */
#if (CRC_USE_HW_ACCEL == STD_ON)
/* 按给定约定做一次硬件计算；reg 为"结果约定"下的起始寄存器值 */
static boolean crc_hw_run_conv(Crc_AlgoType algo, const uint8 *data, uint32 len, uint64 reg,
                               const crc_hw_conv_t *conv, uint64 *result)
{
    const crc_algo_param_t *p = &s_algoParam[algo];
    crc_channel_config_t cfg;
    uint32 raw;

    if ((s_crc == NULL_PTR) || (p->width > 32U)) {
        return FALSE;
    }

    cfg.preset        = crc_preset_none;
    cfg.poly          = (conv->polyShift != 0U) ? (p->poly << (32U - p->width)) : p->poly;
    cfg.poly_width    = p->polyWidth;
    cfg.xorout        = (conv->xorInSw != 0U) ? 0UL : p->xorout;
    cfg.refin         = (p->refin != 0U) ? crc_refin_true : crc_refin_false;
    cfg.refout        = (p->refout != 0U) ? crc_refout_true : crc_refout_false;
    cfg.in_byte_order = crc_in_byte_order_lsb;
    cfg.init          = (conv->initRefl != 0U) ? (uint32)crc_bitrev(reg, p->width) : (uint32)reg;

    /* 通道清零后重配，保证每次都从 INIT_DATA 重新装填 */
    s_crc->CHN[s_hwChannel].CLR = 1U;
    (void)crc_setup_channel_config(s_crc, s_hwChannel, &cfg);

    if ((conv->feedWord != 0U) && (len >= 16U)) {
        crc_calc_large_block_fast(s_crc, s_hwChannel, (uint8_t *)(void *)data, len);
    } else {
        crc_calc_block_bytes(s_crc, s_hwChannel, (uint8_t *)(void *)data, len);
    }

    raw = crc_get_result(s_crc, s_hwChannel) & (uint32)crc_mask(p->width);
    if (conv->xorInSw != 0U) {
        raw ^= p->xorout;
    }
    *result = (uint64)raw;
    return TRUE;
}

/* 自校准：整段路径与链式路径分别找一组"硬件 = 软件表"的约定。
 * 16 组候选 = init 反序 × xorout 软件/硬件 × 喂数方式 × poly 对齐；
 * 每组都要通过 16B 整段 + 24B 整段 + 7B/9B 分段链式三重复核。 */
static void crc_hw_calibrate(void)
{
    static const uint8 pattern[16] = {
        0x00U, 0x11U, 0x22U, 0x33U, 0x44U, 0x55U, 0x66U, 0x77U,
        0x88U, 0x99U, 0xAAU, 0xBBU, 0xCCU, 0xDDU, 0xEEU, 0xFFU
    };
    static const uint8 pattern2[24] = {
        0x5AU, 0xA5U, 0x01U, 0xFEU, 0x7FU, 0x80U, 0x13U, 0x37U,
        0xC4U, 0x2BU, 0x99U, 0x66U, 0xE1U, 0x1EU, 0x00U, 0xFFU,
        0x42U, 0x24U, 0x81U, 0x18U, 0xABU, 0xBAU, 0x5DU, 0xD5U
    };
    Crc_AlgoType algo;
    uint8 mask;

    for (algo = CRC_ALGO_CRC8; algo < CRC_ALGO_COUNT; algo = (Crc_AlgoType)(algo + 1)) {
        const crc_algo_param_t *p = &s_algoParam[algo];
        uint64 reg0;
        uint64 swWhole;
        uint64 swWhole2;
        uint64 swChained;
        uint64 halfReg;

        s_hwWholeConv[algo].ok = 0U;
        s_hwChainConv[algo].ok = 0U;
        if ((p->width > 32U) || (p->hwAllowed == 0U)) {
            continue;
        }
        reg0 = crc_init_of(algo);
        swWhole  = crc_sw_reg_update(algo, reg0, pattern, 16U) ^ crc_xorout_of(algo);
        swWhole2 = crc_sw_reg_update(algo, reg0, pattern2, 24U) ^ crc_xorout_of(algo);
        halfReg  = crc_sw_reg_update(algo, reg0, pattern, 7U);
        swChained = crc_sw_reg_update(algo, (halfReg ^ crc_xorout_of(algo)), &pattern[7], 9U)
                    ^ crc_xorout_of(algo);

        for (mask = 0U; mask < 16U; mask++) {
            crc_hw_conv_t conv;
            uint64 hwWhole;
            uint64 hwWhole2;
            uint64 hwHalf;
            uint64 hwChained;

            conv.initRefl  = (uint8)(mask & 0x01U);
            conv.xorInSw   = (uint8)((mask >> 1) & 0x01U);
            conv.feedWord  = (uint8)(((mask >> 2) & 0x01U) ^ 0x01U);  /* 先试按字喂（更快） */
            conv.polyShift = (uint8)((mask >> 3) & 0x01U);
            conv.ok = 1U;

            /* 整段路径 */
            if ((s_hwWholeConv[algo].ok == 0U) &&
                crc_hw_run_conv(algo, pattern, 16U, reg0, &conv, &hwWhole) &&
                (hwWhole == swWhole) &&
                crc_hw_run_conv(algo, pattern2, 24U, reg0, &conv, &hwWhole2) &&
                (hwWhole2 == swWhole2)) {
                s_hwWholeConv[algo] = conv;
            }
            /* 链式路径 */
            if ((s_hwChainConv[algo].ok == 0U) &&
                crc_hw_run_conv(algo, pattern, 7U, reg0, &conv, &hwHalf) &&
                crc_hw_run_conv(algo, &pattern[7], 9U, hwHalf ^ crc_xorout_of(algo), &conv,
                                &hwChained) &&
                (hwChained == swChained)) {
                s_hwChainConv[algo] = conv;
            }
            if ((s_hwWholeConv[algo].ok != 0U) && (s_hwChainConv[algo].ok != 0U)) {
                break;
            }
        }
    }
}
#endif /* CRC_USE_HW_ACCEL */

/* 惰性初始化：开外设时钟 + 自校准（SWS 没有 Init API，故放在首次 Calculate） */
static void crc_hw_ensure_ready(void)
{
    if (s_hwReady) {
        return;
    }
    s_hwReady = TRUE;

#if (CRC_USE_HW_ACCEL == STD_ON)
    if (!s_hwEnable) {
        return;
    }
    clock_add_to_group((clock_name_t)Crc_Config.hwClockId, 0U);
    s_crc = (CRC_Type *)(uintptr_t)Crc_Config.hwBaseAddress;
    s_hwChannel = (uint8)(Crc_Config.hwChannel & 0x07U);
    crc_hw_calibrate();
#endif
}

/* ============================== 统一计算入口 ============================== */
static uint64 crc_calc(Crc_AlgoType algo, const uint8 *data, uint32 length, uint64 reg,
                       boolean chained)
{
    crc_hw_ensure_ready();
#if (CRC_USE_HW_ACCEL == STD_ON)
    if (s_hwEnable && (length >= (uint32)CRC_HW_MIN_LENGTH)) {
        const crc_hw_conv_t *conv = (chained != FALSE) ? &s_hwChainConv[algo] : &s_hwWholeConv[algo];
        uint64 hwResult;
        if ((conv->ok != 0U) && crc_hw_run_conv(algo, data, length, reg, conv, &hwResult)) {
            s_hwCalls++;
            return hwResult;
        }
    }
    s_swFallbacks++;
#endif
    return crc_sw_reg_update(algo, reg, data, length) ^ crc_xorout_of(algo);
}


/* 8 颗 CAN 状态灯 -> GPIOF, 全部配置为输出(默认熄灭), 供车灯/跑马灯类例程使用.
 * 注意: 这些引脚同时被 CAN 例程用作状态灯, 不应该与 CAN 收发同时改写. */
void init_canled_bank_pins(void)
{
    static const uint8_t pins[8] = { 26U, 18U, 20U, 16U, 22U, 21U, 23U, 19U };
    HPM_IOC->PAD[IOC_PAD_PF26].FUNC_CTL = IOC_PF26_FUNC_CTL_GPIO_F_26;
    HPM_IOC->PAD[IOC_PAD_PF18].FUNC_CTL = IOC_PF18_FUNC_CTL_GPIO_F_18;
    HPM_IOC->PAD[IOC_PAD_PF20].FUNC_CTL = IOC_PF20_FUNC_CTL_GPIO_F_20;
    HPM_IOC->PAD[IOC_PAD_PF16].FUNC_CTL = IOC_PF16_FUNC_CTL_GPIO_F_16;
    HPM_IOC->PAD[IOC_PAD_PF22].FUNC_CTL = IOC_PF22_FUNC_CTL_GPIO_F_22;
    HPM_IOC->PAD[IOC_PAD_PF21].FUNC_CTL = IOC_PF21_FUNC_CTL_GPIO_F_21;
    HPM_IOC->PAD[IOC_PAD_PF23].FUNC_CTL = IOC_PF23_FUNC_CTL_GPIO_F_23;
    HPM_IOC->PAD[IOC_PAD_PF19].FUNC_CTL = IOC_PF19_FUNC_CTL_GPIO_F_19;
    for (uint32_t i = 0; i < 8U; i++) {
        gpio_set_pin_output(HPM_GPIO0, GPIO_DO_GPIOF, pins[i]);
        gpio_write_pin(HPM_GPIO0, GPIO_DO_GPIOF, pins[i], 0U);
    }
}

/* SPI1 master: PC10=SCLK PC11=CS PC12=MISO PC13=MOSI (ALT5), 高速档 SR/SPD */
void init_spi1_master_pins(void)
{
    /* 关键: SPI master 的 RX 移位时钟来自 SCLK pad 内部回送(LOOP_BACK), 不开则 master 永远收不到 MISO. */
    HPM_IOC->PAD[IOC_PAD_PC10].FUNC_CTL = IOC_PC10_FUNC_CTL_SPI1_SCLK | IOC_PAD_FUNC_CTL_LOOP_BACK_MASK;
    HPM_IOC->PAD[IOC_PAD_PC10].PAD_CTL = IOC_PAD_PAD_CTL_SR_SET(1) | IOC_PAD_PAD_CTL_SPD_SET(3);
    HPM_IOC->PAD[IOC_PAD_PC11].FUNC_CTL = IOC_PC11_FUNC_CTL_SPI1_CS_0;
    HPM_IOC->PAD[IOC_PAD_PC11].PAD_CTL = IOC_PAD_PAD_CTL_SR_SET(1) | IOC_PAD_PAD_CTL_SPD_SET(3);
    HPM_IOC->PAD[IOC_PAD_PC12].FUNC_CTL = IOC_PC12_FUNC_CTL_SPI1_MISO;
    HPM_IOC->PAD[IOC_PAD_PC12].PAD_CTL = IOC_PAD_PAD_CTL_SR_SET(1) | IOC_PAD_PAD_CTL_SPD_SET(3);
    HPM_IOC->PAD[IOC_PAD_PC13].FUNC_CTL = IOC_PC13_FUNC_CTL_SPI1_MOSI;
    HPM_IOC->PAD[IOC_PAD_PC13].PAD_CTL = IOC_PAD_PAD_CTL_SR_SET(1) | IOC_PAD_PAD_CTL_SPD_SET(3);
}

/* SPI3 slave: PA26=SCLK PA27=CS_0 PA28=MISO PA29=MOSI (ALT5).
 * slave 侧 SCLK/CS/MOSI 是输入, 打开上拉+施密特; MISO 是输出. */
void init_spi3_slave_pins(void)
{
    HPM_IOC->PAD[IOC_PAD_PA26].FUNC_CTL = IOC_PA26_FUNC_CTL_SPI3_SCLK | IOC_PAD_FUNC_CTL_LOOP_BACK_MASK;
    HPM_IOC->PAD[IOC_PAD_PA26].PAD_CTL = IOC_PAD_PAD_CTL_PE_SET(1) | IOC_PAD_PAD_CTL_PS_SET(1)
        | IOC_PAD_PAD_CTL_HYS_SET(1);
    HPM_IOC->PAD[IOC_PAD_PA27].FUNC_CTL = IOC_PA27_FUNC_CTL_SPI3_CS_0;
    HPM_IOC->PAD[IOC_PAD_PA27].PAD_CTL = IOC_PAD_PAD_CTL_PE_SET(1) | IOC_PAD_PAD_CTL_PS_SET(1)
        | IOC_PAD_PAD_CTL_HYS_SET(1);
    /* 标准 4 线 SPI 接线: master MOSI -> slave MOSI(PA29), master MISO <- slave MISO(PA28).
     * 2026-10-30 实测用户当前接线是交叉的(PC13-PA28 / PC12-PA29), 需要把 PA28/PA29 两根线互换;
     * 用 spi_ms_wires 命令可一键探测实际接线. */
    HPM_IOC->PAD[IOC_PAD_PA28].FUNC_CTL = IOC_PA28_FUNC_CTL_SPI3_MISO;
    HPM_IOC->PAD[IOC_PAD_PA28].PAD_CTL = IOC_PAD_PAD_CTL_SR_SET(1) | IOC_PAD_PAD_CTL_SPD_SET(3);
    HPM_IOC->PAD[IOC_PAD_PA29].FUNC_CTL = IOC_PA29_FUNC_CTL_SPI3_MOSI;
    HPM_IOC->PAD[IOC_PAD_PA29].PAD_CTL = IOC_PAD_PAD_CTL_PE_SET(1) | IOC_PAD_PAD_CTL_PS_SET(1)
        | IOC_PAD_PAD_CTL_HYS_SET(1);
}


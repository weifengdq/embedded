/*
 * onsemi T30HM1TS2500 (S2500) 10BASE-T1S MAC-PHY register map.
 *
 * Register access goes through OPEN Alliance 10BASE-T1x MAC-PHY SPI
 * control transactions; every register is 32-bit and addressed by
 * (MMS, ADDR).
 */
#ifndef _S2500_REGS_H
#define _S2500_REGS_H

/* Memory Map Selectors */
#define S2500_MMS_STD		0
#define S2500_MMS_MAC		1
#define S2500_MMS_PCS		2
#define S2500_MMS_PMA		3
#define S2500_MMS_PLCA		4
#define S2500_MMS_VENDOR	12

/* ---- MMS0: standard control/status ---- */
#define S2500_REG_IDVER		0x0000
#define S2500_REG_PHYID		0x0001
#define S2500_REG_STDCAP	0x0002
#define S2500_REG_RESET		0x0003
#define S2500_REG_CONFIG0	0x0004
#define S2500_REG_STATUS0	0x0008
#define S2500_REG_STATUS1	0x0009
#define S2500_REG_BUFSTS	0x000b
#define S2500_REG_IMSK0		0x000c
#define S2500_REG_IMSK1		0x000d
#define S2500_REG_PHY_CTRL	0xff00
#define S2500_REG_PHY_STATUS	0xff01
#define S2500_REG_PHY_IDH	0xff02
#define S2500_REG_PHY_IDL	0xff03

#define S2500_IDVER_S2500	0x11

#define S2500_CONFIG0_SYNC	BIT(15)
#define S2500_CONFIG0_TXFCSVE	BIT(14)
#define S2500_CONFIG0_CSARFE	BIT(13)
#define S2500_CONFIG0_ZARFE	BIT(12)
#define S2500_CONFIG0_TXCTHRESH_8 (2u << 10)
#define S2500_CONFIG0_TXCTE	BIT(9)
#define S2500_CONFIG0_RXCTE	BIT(8)
#define S2500_CONFIG0_FTSE	BIT(7)
#define S2500_CONFIG0_FTSS	BIT(6)
#define S2500_CONFIG0_PROTE	BIT(5)
#define S2500_CONFIG0_CPS_64	(6u << 0)
#define S2500_CONFIG0_CPS_MASK	(7u << 0)

#define S2500_STATUS0_CDPE	BIT(12)
#define S2500_STATUS0_TXFCSE	BIT(11)
#define S2500_STATUS0_TTSCAC	BIT(10)
#define S2500_STATUS0_TTSCAB	BIT(9)
#define S2500_STATUS0_TTSCAA	BIT(8)
#define S2500_STATUS0_PHYINT	BIT(7)
#define S2500_STATUS0_RESETC	BIT(6)
#define S2500_STATUS0_HDRE	BIT(5)
#define S2500_STATUS0_LOFE	BIT(4)
#define S2500_STATUS0_RXBOE	BIT(3)
#define S2500_STATUS0_TXBUE	BIT(2)
#define S2500_STATUS0_TXBOE	BIT(1)
#define S2500_STATUS0_TXPE	BIT(0)
#define S2500_STATUS0_ERR_MASK	0x00001fbfu

#define S2500_BUFSTS_TXC_SHIFT	8
#define S2500_BUFSTS_TXC_MASK	0x0000ff00u
#define S2500_BUFSTS_RCA_MASK	0x000000ffu

#define S2500_PHYSTS_S10M	BIT(11)
#define S2500_PHYSTS_LNOK	BIT(5)
#define S2500_PHYSTS_RJAB	BIT(4)
#define S2500_PHYSTS_LKST	BIT(2)
#define S2500_PHYSTS_LJAB	BIT(1)
#define S2500_PHYCTRL_RESET	BIT(15)
#define S2500_PHYCTRL_LOOPBACK	BIT(14)
#define S2500_PHYCTRL_LCTL	BIT(12)

/* ---- MMS1: MAC ---- */
#define S2500_REG_MCONTROL0	0x0000
#define S2500_REG_MADDRFILT0L	0x0010
#define S2500_REG_MADDRFILT0H	0x0011
#define S2500_REG_MADDRMASK0L	0x0020
#define S2500_REG_MADDRMASK0H	0x0021
#define S2500_REG_MST_BASE	0x0030

#define S2500_MC_IPGNF		BIT(21)
#define S2500_MC_BKOD		BIT(20)
#define S2500_MC_NFCSF		BIT(19)
#define S2500_MC_MCSF		BIT(18)
#define S2500_MC_BCSF		BIT(17)
#define S2500_MC_ADRF		BIT(16)
#define S2500_MC_FCSA		BIT(8)
#define S2500_MC_TXEN		BIT(1)
#define S2500_MC_RXEN		BIT(0)

#define S2500_FILT_EN		BIT(31)

/* MAC statistics, 0x30..0x52 */
#define S2500_MST_TX_OCTETS_L	0x0030
#define S2500_MST_TX_OCTETS_H	0x0031
#define S2500_MST_TX_FRAMES	0x0032
#define S2500_MST_TX_BCAST	0x0033
#define S2500_MST_TX_MCAST	0x0034
#define S2500_MST_TX_UNDERFLOW	0x003b
#define S2500_MST_TX_SINGLECOL	0x003c
#define S2500_MST_TX_MULTICOL	0x003d
#define S2500_MST_TX_EXCESSCOL	0x003e
#define S2500_MST_TX_DEFERRED	0x003f
#define S2500_MST_TX_CRSERR	0x0040
#define S2500_MST_RX_OCTETS_L	0x0041
#define S2500_MST_RX_OCTETS_H	0x0042
#define S2500_MST_RX_FRAMES	0x0043
#define S2500_MST_RX_BCAST	0x0044
#define S2500_MST_RX_MCAST	0x0045
#define S2500_MST_RX_RUNTS	0x004c
#define S2500_MST_RX_TOOLONG	0x004d
#define S2500_MST_RX_FCSERR	0x004e
#define S2500_MST_RX_SYMBOLERR	0x004f
#define S2500_MST_RX_ALIGNERR	0x0050
#define S2500_MST_RX_OVERFLOW	0x0051
#define S2500_MST_RX_DROPPED	0x0052
#define S2500_MST_LAST		0x0052
#define S2500_MST_COUNT		(S2500_MST_LAST - S2500_REG_MST_BASE + 1)

/* ---- MMS2: PCS ---- */
#define S2500_REG_PCSCTL	0x08f3
#define S2500_REG_PCSSTATUS	0x08f4
#define S2500_REG_PCSDIAG1	0x08f5
#define S2500_REG_PCSDIAG2	0x08f6
#define S2500_PCSCTL_LOOP	BIT(14)

/* ---- MMS3: PMA ---- */
#define S2500_REG_PMACTL	0x08f9
#define S2500_REG_PMASTATUS	0x08fa
#define S2500_PMACTL_LOOP	BIT(0)

/* ---- MMS4: PLCA / diagnostics ---- */
#define S2500_REG_PLCAIDVER	0xca00
#define S2500_REG_PLCACTL0	0xca01
#define S2500_REG_PLCACTL1	0xca02
#define S2500_REG_PLCASTATUS	0xca03
#define S2500_REG_PLCATOTMR	0xca04
#define S2500_REG_PLCABURST	0xca05
#define S2500_REG_PLCADIAG	0xca06

#define S2500_PLCA_EN		BIT(15)
#define S2500_PLCA_RST		BIT(14)
#define S2500_PLCA_NCNT_SHIFT	8
#define S2500_PLCA_ID_MASK	0xffu
#define S2500_PLCA_PST		BIT(15)

#define S2500_REG_ADFCAP	0xcc00
#define S2500_REG_HDD		0xcc01
#define S2500_REG_DCQ_SQI	0xcc03
#define S2500_REG_DCQ_SQIP	0xcc04

#define S2500_ADFCAP_HDD1W	BIT(11)
#define S2500_ADFCAP_SQI	BIT(0)

#define S2500_HDD_CTRL		BIT(15)
#define S2500_HDD_READY		BIT(14)
#define S2500_HDD_START		BIT(13)
#define S2500_HDD_1W_ST		BIT(3)
#define S2500_HDD_VALID		BIT(2)
#define S2500_HDD_SHORT_OPEN_MASK 0x3u

#define S2500_SQI_MASK		0x7u
#define S2500_SQIP_MASK		0xffu

#define S2500_REG_ONIPVER	0x8000
#define S2500_REG_TWEAKS1	0x8001
#define S2500_REG_PLCAEXT	0x8002
#define S2500_REG_PMATUNE0	0x8003
#define S2500_REG_WUPTUNE	0x8007

#define S2500_PLCAEXT_PRECEDENCE BIT(15)
#define S2500_PLCAEXT_CRPS	BIT(4)
#define S2500_PLCAEXT_CREN	BIT(2)
#define S2500_PLCAEXT_LDEN	BIT(1)
#define S2500_PLCAEXT_LDR	BIT(0)

/* ---- MMS12: onsemi vendor ---- */
#define S2500_REG_PHYIRQM	0x0010
#define S2500_REG_PHYIRQS	0x0011
#define S2500_REG_DIOCFG0	0x0012
#define S2500_REG_ONICVER	0x1000
#define S2500_REG_TWEAKS2	0x1001
#define S2500_REG_MACID0	0x1002
#define S2500_REG_MACID1	0x1003

#define S2500_TWEAKS2_TXSLW_SHIFT 2
#define S2500_TWEAKS2_CLKO_ENA	BIT(4)

/* DIOCFG0: per-DIO byte: [7]SLW [6]PEN [5]PUD [4:1]FN [0]VAL */
#define S2500_DIO_SHIFT(n)	((n) ? 8 : 0)
#define S2500_DIO_SLW(n)	BIT(S2500_DIO_SHIFT(n) + 7)
#define S2500_DIO_PEN(n)	BIT(S2500_DIO_SHIFT(n) + 6)
#define S2500_DIO_PUD(n)	BIT(S2500_DIO_SHIFT(n) + 5)
#define S2500_DIO_FN(n, fn)	(((u32)(fn) & 0xfu) << (S2500_DIO_SHIFT(n) + 1))
#define S2500_DIO_VAL(n, v)	((u32)((v) ? 1u : 0u) << S2500_DIO_SHIFT(n))

#define S2500_DIOFN_DISABLE	0x0
#define S2500_DIOFN_GPIO	0x1
#define S2500_DIOFN_LED_LINKCTL	0x4
#define S2500_DIOFN_LED_PLCASTS	0x5
#define S2500_DIOFN_LED_TX	0x6
#define S2500_DIOFN_LED_RX	0x7
#define S2500_DIOFN_LED_TXRX	0xf

#endif /* _S2500_REGS_H */

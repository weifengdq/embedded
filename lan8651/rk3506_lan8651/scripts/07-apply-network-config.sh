#!/bin/bash
# 应用“网络配置 + 常用网络工具 + PATH 补全”修改（幂等，可重复执行）
#
# 内容：
#   1) eth0 改为 DHCP（/etc/network/interfaces），并让 dhcpcd 不再管理 eth0（避免双客户端）
#   2) 补全登录 shell 的 PATH（/bin:/sbin），使 ip/ifconfig/route/reboot/insmod 等可用
#   3) buildroot 增加 iw、curl（libcurl）等常用网络工具
#   4) 删除 legacy 的 BR2_PACKAGE_CURL（它会导致 BR2_LEGACY=y 与构建失败）
#
# 之后重新编译： source scripts/04-setup-env.sh && bash scripts/05-build-all.sh
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"; . "$HERE/lib/common.sh"

[ -d "$SDK_DIR/buildroot" ] || die "SDK 不存在：$SDK_DIR"
OV="$SDK_DIR/buildroot/board/rockchip/rk3506/fs-overlay"
DEF="$SDK_DIR/buildroot/configs/rockchip_rk3506_defconfig"

mkdir -p "$OV/etc/network" "$OV/etc/profile.d"

# 1) eth0 -> DHCP
cat > "$OV/etc/network/interfaces" <<'EOF'
# interface file auto-generated by buildroot
# [rk3506_1] eth0 使用 DHCP（由 busybox ifup 调用 udhcpc 获取地址）

auto lo
iface lo inet loopback

auto eth0
iface eth0 inet dhcp

source-directory /etc/network/interfaces.d
EOF
log "已写入 DHCP interfaces：$OV/etc/network/interfaces"

# 2) PATH
cat > "$OV/etc/profile.d/00-path.sh" <<'EOF'
# [rk3506_1] 补全常用命令路径（ip/ifconfig/route/reboot/insmod 等在 /sbin）
export PATH="/bin:/sbin:/usr/bin:/usr/sbin"
EOF
log "已写入 PATH 补全：$OV/etc/profile.d/00-path.sh"

# 3) dhcpcd 不管理 eth0（基于 target 现有 dhcpcd.conf 复制后追加）
BASECFG="$SDK_DIR/buildroot/output/rockchip_rk3506/target/etc/dhcpcd.conf"
if [ -f "$BASECFG" ]; then
  cp -f "$BASECFG" "$OV/etc/dhcpcd.conf"
fi
if [ -f "$OV/etc/dhcpcd.conf" ] && ! grep -q "denyinterfaces eth0" "$OV/etc/dhcpcd.conf"; then
  cat >> "$OV/etc/dhcpcd.conf" <<'EOF'

# [rk3506_1] eth0 由 /etc/network/interfaces 的 dhcp(udhcpc) 管理，dhcpcd 不插手
denyinterfaces eth0
EOF
  log "已在 dhcpcd.conf 追加 denyinterfaces eth0"
else
  log "dhcpcd.conf 已配置或不可用，跳过"
fi

# 4) buildroot 软件包配置
sed -i '/^BR2_PACKAGE_CURL=y$/d' "$DEF" || true   # legacy，必须移除
for opt in BR2_PACKAGE_IW BR2_PACKAGE_LIBCURL BR2_PACKAGE_LIBCURL_CURL BR2_PACKAGE_LIBCURL_OPENSSL; do
  grep -q "^${opt}=y$" "$DEF" || echo "${opt}=y" >> "$DEF"
done
# 清理会带入 BR2_LEGACY 的旧 .config，避免 “legacy configuration” 报错
rm -f "$SDK_DIR/buildroot/output/rockchip_rk3506/.config" \
      "$SDK_DIR/buildroot/output/rockchip_rk3506/.config.orig"
log "已更新 buildroot defconfig（iw/libcurl），并清理旧 .config"

log "完成。请重新编译 rootfs/firmware 并重新制卡。"

#!/bin/bash
# 把 LAN8651 的接口命名/网络配置写进 Buildroot overlay（供最终镜像使用）
#
# 背景：LAN865x 是 built-in，probe 比 RK GMAC 早，会抢到 eth0；RK GMAC 变成 eth1。
#       这会让原来的 eth0 DHCP 配到 T1S 上，上行网口反而没 IP。
# 做法：
#   1) /etc/init.d/S39rename-t1s：按 /sys/class/net/*/device 把 spi0.0 重命名为 t1s0，
#      把 ff4c8000.ethernet 重命名为 eth0（在 S40network 之前执行）。
#   2) /etc/network/interfaces：eth0=DHCP（上行），t1s0=192.168.1.100/24。
#
# 幂等。之后重编 rootfs/firmware 才会进镜像；当前板卡可手工部署同样的文件。
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"; . "$HERE/lib/common.sh"

OV="$SDK_DIR/buildroot/board/rockchip/rk3506/fs-overlay"
[ -d "$SDK_DIR/buildroot" ] || die "SDK/buildroot 不存在：$SDK_DIR"

mkdir -p "$OV/etc/init.d" "$OV/etc/network"

cat > "$OV/etc/init.d/S39rename-t1s" <<'EOF'
#!/bin/sh
# Rename the LAN8651 (spi0.0) to t1s0 and keep the RK GMAC as eth0.
# Needed because the built-in LAN865x driver probes before the GMAC and
# otherwise steals eth0.
case "$1" in
  start)
    for n in /sys/class/net/*; do
      name=${n##*/}
      dev=$(readlink -f "$n/device" 2>/dev/null)
      case "$dev" in
        *spi0.0*)
          if [ "$name" != "t1s0" ]; then
            ip link set dev "$name" down 2>/dev/null
            ip link set dev "$name" name t1s0 2>/dev/null
          fi
          ;;
      esac
    done
    for n in /sys/class/net/*; do
      name=${n##*/}
      dev=$(readlink -f "$n/device" 2>/dev/null)
      case "$dev" in
        *ff4c8000.ethernet*)
          if [ "$name" != "eth0" ]; then
            ip link set dev "$name" down 2>/dev/null
            ip link set dev "$name" name eth0 2>/dev/null
          fi
          ;;
      esac
    done
    ;;
esac
exit 0
EOF
chmod +x "$OV/etc/init.d/S39rename-t1s"
log "已写入 $OV/etc/init.d/S39rename-t1s"

# interfaces：保留原有 eth0 DHCP，追加 t1s0 静态
IF="$OV/etc/network/interfaces"
if [ ! -f "$IF" ]; then
  cat > "$IF" <<'EOF'
# interface file auto-generated by buildroot
auto lo
iface lo inet loopback

auto eth0
iface eth0 inet dhcp

source-directory /etc/network/interfaces.d
EOF
fi
if grep -q "^iface t1s0 inet" "$IF"; then
  log "$IF 已包含 t1s0，跳过"
else
  cat >> "$IF" <<'EOF'

# LAN8651 10BASE-T1S
auto t1s0
iface t1s0 inet static
    address 192.168.1.100
    netmask 255.255.255.0
EOF
  log "已在 $IF 追加 t1s0 静态配置"
fi

cat <<EOF

完成。重编 rootfs/firmware 后生效：
  cd "\$SDK_DIR" && ./build.sh rootfs && ./build.sh firmware

当前板卡手工部署（可选）：
  scp $OV/etc/init.d/S39rename-t1s root@<ip>:/etc/init.d/
  ssh root@<ip> 'chmod +x /etc/init.d/S39rename-t1s'
  # 再把 t1s0 段追加到 /etc/network/interfaces
EOF
